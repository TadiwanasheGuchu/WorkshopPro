# The ledger maintains stock_levels.on_hand. Every movement insert adds to the balance
# for its part and location; the on_hand >= 0 check rejects movements that would make
# stock negative. balance_after is recorded on the movement for traceability.
LEDGER_SQL = """
CREATE FUNCTION stock_movement_apply() RETURNS trigger AS $$
DECLARE
    new_balance NUMERIC(12, 2);
BEGIN
    PERFORM set_config('workshoppro.stock_ledger', 'on', true);
    -- Update first: INSERT ... ON CONFLICT would check constraints against the
    -- proposed new row (a negative quantity) before resolving the conflict.
    UPDATE stock_levels SET on_hand = on_hand + NEW.quantity, updated_at = now()
    WHERE location_id = NEW.location_id AND part_id = NEW.part_id
    RETURNING on_hand INTO new_balance;
    IF NOT FOUND THEN
        INSERT INTO stock_levels (location_id, part_id, organisation_id, branch_id, on_hand)
        VALUES (NEW.location_id, NEW.part_id, NEW.organisation_id, NEW.branch_id, NEW.quantity)
        RETURNING on_hand INTO new_balance;
    END IF;
    PERFORM set_config('workshoppro.stock_ledger', 'off', true);
    NEW.balance_after := new_balance;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER stock_movements_apply
BEFORE INSERT ON stock_movements
FOR EACH ROW EXECUTE FUNCTION stock_movement_apply();

CREATE FUNCTION stock_movements_append_only() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'stock movements are append-only; record a correcting movement';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER stock_movements_append_only
BEFORE UPDATE OR DELETE ON stock_movements
FOR EACH ROW EXECUTE FUNCTION stock_movements_append_only();

-- on_hand may only change through the ledger trigger above.
CREATE FUNCTION stock_levels_protect_on_hand() RETURNS trigger AS $$
BEGIN
    IF current_setting('workshoppro.stock_ledger', true) IS DISTINCT FROM 'on' THEN
        IF TG_OP = 'INSERT' AND NEW.on_hand <> 0 THEN
            RAISE EXCEPTION 'stock on hand changes only through stock movements';
        ELSIF TG_OP = 'UPDATE' AND NEW.on_hand IS DISTINCT FROM OLD.on_hand THEN
            RAISE EXCEPTION 'stock on hand changes only through stock movements';
        ELSIF TG_OP = 'DELETE' THEN
            RAISE EXCEPTION 'stock levels cannot be deleted';
        END IF;
    END IF;
    RETURN COALESCE(NEW, OLD);
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER stock_levels_protect_on_hand
BEFORE INSERT OR UPDATE OR DELETE ON stock_levels
FOR EACH ROW EXECUTE FUNCTION stock_levels_protect_on_hand();
"""


