def _seed_default_templates() -> None:
    from app.services.default_inspection import DEFAULT_ITEMS

    conn = op.get_bind()
    orgs = conn.execute(
        sa.text(
            "SELECT o.id FROM organisations o WHERE NOT EXISTS "
            "(SELECT 1 FROM inspection_templates t WHERE t.organisation_id = o.id)"
        )
    ).scalars()
    for org_id in orgs:
        template_id = conn.execute(
            sa.text(
                "INSERT INTO inspection_templates (id, organisation_id, name, description, is_default) "
                "VALUES (gen_random_uuid(), :org, :name, :description, true) RETURNING id"
            ),
            {"org": org_id, "name": _TEMPLATE_NAME, "description": _TEMPLATE_DESCRIPTION},
        ).scalar_one()
        for position, (section, label, guidance) in enumerate(DEFAULT_ITEMS):
            conn.execute(
                sa.text(
                    "INSERT INTO inspection_template_items "
                    "(id, template_id, section, label, guidance, position) "
                    "VALUES (gen_random_uuid(), :t, :section, :label, :guidance, :position)"
                ),
                {"t": template_id, "section": section, "label": label, "guidance": guidance, "position": position},
            )


